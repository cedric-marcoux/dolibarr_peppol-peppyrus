/**
 * Merge PHPStan baselines generated against several Dolibarr versions into dev/phpstan/baseline.php.
 * Per report (message, identifier, file) the highest count is kept, so the check passes on every version.
 *
 * Usage (from the root), after generating one baseline per Dolibarr version in dev/phpstan/:
 *   DOLIBARR_HTDOCS=/path/to/dolibarr-18.0/htdocs phpstan analyse --generate-baseline=dev/phpstan/baseline-18.php
 *   DOLIBARR_HTDOCS=/path/to/dolibarr-24.0/htdocs phpstan analyse --generate-baseline=dev/phpstan/baseline-24.php
 *   php dev/phpstan/merge-baselines.php dev/phpstan/baseline-18.php dev/phpstan/baseline-24.php
 */
if ($argc < 2) {
	fwrite(STDERR, "Usage: php dev/phpstan/merge-baselines.php <baseline.php> [<baseline.php> ...]\n");
	exit(1);
}
$merged = array();
foreach (array_slice($argv, 1) as $file) {
	$entries = (require $file)['parameters']['ignoreErrors'];
	foreach ($entries as $e) {
		$path = (string) preg_replace('#^.*/\.\./\.\./#', '', $e['path']);
		$key = $e['message']."\0".($e['identifier'] ?? '')."\0".$path;
		if (!isset($merged[$key]) || $e['count'] > $merged[$key]['count']) {
			$merged[$key] = array('message' => $e['message'], 'identifier' => $e['identifier'] ?? null, 'count' => (int) $e['count'], 'path' => $path);
		}
	}
}
ksort($merged);
$out = "<?php declare(strict_types = 1);\n\n// Generated by dev/phpstan/merge-baselines.php: reports of the existing code when PHPStan was introduced.\n// New reports make the check fail; fix them instead of adding them here.\n\$ignoreErrors = [];\n";
foreach ($merged as $e) {
	$out .= "\$ignoreErrors[] = [\n";
	$out .= "\t'message' => ".var_export($e['message'], true).",\n";
	if ($e['identifier'] !== null) {
		$out .= "\t'identifier' => ".var_export($e['identifier'], true).",\n";
	}
	$out .= "\t'count' => ".$e['count'].",\n";
	$out .= "\t'path' => __DIR__ . '/../../".$e['path']."',\n";
	$out .= "];\n";
}
$out .= "\nreturn ['parameters' => ['ignoreErrors' => \$ignoreErrors]];\n";
file_put_contents(__DIR__.'/baseline.php', $out);
echo count($merged)." entries written to dev/phpstan/baseline.php\n";
